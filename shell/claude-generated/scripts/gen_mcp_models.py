"""Write self-contained build123d model files (no scipy/shapely) with the solved sections baked in.

usage: python -I gen_mcp_models.py <out_dir_with_A_B_C_stations> <dest_dir> [A B C]
The files run inside build123d-mcp (execute_file) or plain python with build123d.
"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from scipy.interpolate import PchipInterpolator
import params as P

TEMPLATE = '''"""Snips shell outer skin, option {key} ({name}). Generated by gen_mcp_models.py from params.py.
Change the numbers in params.py and regenerate; the rows below are the solved sections."""
import math
from build123d import *

CX = {cx}
EQ = {eq}
# (y, width, z_front, z_back, n_front, n_back)
ROWS = {rows}


def se_points(w, zf, zb, nf, nb, eq, n=64):
    zc = zb + eq * (zf - zb)
    bf, bb, a = zf - zc, zc - zb, w / 2
    pts = []
    for k in range(n):
        t = 2 * math.pi * k / n
        c, s = math.cos(t), math.sin(t)
        e, b = (nf, bf) if s >= 0 else (nb, bb)
        pts.append((CX + a * math.copysign(abs(c) ** (2 / e), c), 0,
                    zc + b * math.copysign(abs(s) ** (2 / e), s)))
    return pts


faces = []
for y, w, zf, zb, nf, nb in ROWS:
    pts = [(x, y, z) for x, _, z in se_points(w, zf, zb, nf, nb, EQ)]
    faces.append(Face(Wire([Edge.make_spline(pts, periodic=True)])))
skin = loft(faces)
show(skin, "shell_{key}")
'''


def dense(rows, loft_step, end_zone, end_step):
    a = np.array(rows)
    fs = [PchipInterpolator(a[:, 0], a[:, k]) for k in range(1, 6)]
    y0, y1 = a[0, 0], a[-1, 0]
    ys = np.concatenate([np.arange(y0, y1, loft_step), [y1],
                         np.arange(y0, y0 + end_zone, end_step),
                         np.arange(y1 - end_zone, y1, end_step)])
    ys = np.unique(np.round(ys, 3))
    return [[round(float(y), 3)] + [round(float(f(y)), 3) for f in fs] for y in ys]


if __name__ == "__main__":
    src, dest = sys.argv[1], sys.argv[2]
    keys = sys.argv[3:] or list(P.SHAPES)
    os.makedirs(dest, exist_ok=True)
    for k in keys:
        rows = json.load(open(os.path.join(src, k, "stations.json")))
        d = dense(rows, 3.0, 9.0, 1.0)
        body = TEMPLATE.format(key=k, name=P.SHAPES[k]["name"], cx=P.BOARD_W / 2,
                               eq=P.SHAPES[k]["eq"], rows=json.dumps(d))
        open(os.path.join(dest, "model_%s.py" % k), "w").write(body)
        print(k, len(d), "sections")
