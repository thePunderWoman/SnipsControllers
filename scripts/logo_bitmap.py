#!/usr/bin/env python3
"""Generate a small 1-bit Snips logo header for the OLED status screens.

Scales graphics/snips-logo.png to a target height, thresholds its alpha
channel, trims empty rows and columns, and writes the result as a C++
header in the row-major, MSB-first-per-byte format FrameBuffer::drawBitmap()
takes (the same format as include/snips_logo_bitmap.h).

Usage:
    python3 scripts/logo_bitmap.py --height 40 \
        --out include/snips_logo_small_bitmap.h
"""

import argparse
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "graphics" / "snips-logo.png"

# Alpha at or above this, after scaling, counts as a lit pixel. Lower than
# the midpoint so the logo's thin strokes survive the downscale.
ALPHA_THRESHOLD = 110


def logo_rows(height):
    alpha = Image.open(SOURCE).convert("RGBA").getchannel("A")
    alpha = alpha.crop(alpha.point(lambda v: 255 if v >= 128 else 0).getbbox())
    width = round(alpha.width * height / alpha.height)
    scaled = alpha.resize((width, height), Image.LANCZOS)
    rows = [
        [scaled.getpixel((x, y)) >= ALPHA_THRESHOLD for x in range(width)]
        for y in range(height)
    ]
    rows = [r for r in rows if any(r)]
    used = [x for x in range(width) if any(r[x] for r in rows)]
    return [r[used[0] : used[-1] + 1] for r in rows]


def header(rows, height):
    width = len(rows[0])
    byte_width = (width + 7) // 8
    data = []
    for row in rows:
        for b in range(byte_width):
            value = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < width and row[x]:
                    value |= 0x80 >> bit
            data.append(f"0x{value:02x}")
    lines = [
        ", ".join(data[i : i + 12]) + "," for i in range(0, len(data), 12)
    ]
    body = "\n".join("    " + line for line in lines)
    return f"""#pragma once

#include <cstdint>

// Generated by scripts/logo_bitmap.py --height {height}; do not edit by
// hand. A small Snips logo for the status screens (status_screen.h), from
// graphics/snips-logo.png with empty rows and columns trimmed. Row-major,
// MSB-first per byte, the format FrameBuffer::drawBitmap() takes.
namespace SnipsLogoSmall {{

constexpr int kWidth = {width};
constexpr int kHeight = {len(rows)};
constexpr int kByteWidth = (kWidth + 7) / 8;

constexpr uint8_t kBitmap[kByteWidth * kHeight] = {{
{body}
}};

}}  // namespace SnipsLogoSmall
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--height", type=int, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.write_text(header(logo_rows(args.height), args.height))


if __name__ == "__main__":
    main()
